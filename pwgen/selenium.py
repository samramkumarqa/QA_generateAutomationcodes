def page_java(p: PageModel) -> str:
    login = ""
    imports = "import org.openqa.selenium.WebDriver;\n"
    if p.is_login:
        parent, call = "BasePage", f'super(driver, {jstr(p.name)});'
        user, pwd, submit = _login_parts(p)
        if user and pwd and submit:
            imports += f"\nimport {PKG}.utils.Config;\n"
            login = f"""
    /** Log in with APP_USERNAME / APP_PASSWORD from .env. */
    public void login() {{
        login(Config.username(), Config.password());
    }}

    public void login(String username, String password) {{
        if (username.isBlank() || password.isBlank()) {{
            throw new IllegalStateException("No login credentials: copy .env.example to .env and set APP_USERNAME and APP_PASSWORD");
        }}
        open();
        type({constant(user.name)}, username);
        type({constant(pwd.name)}, password);
        click({constant(submit.name)});
        // Fail here with a clear message, not on the next page's first step.
        if (!isHidden({constant(pwd.name)})) {{
            throw new IllegalStateException("Login as \\"" + username + "\\" didn't succeed: still on the login page. Check APP_USERNAME / APP_PASSWORD in .env");
        }}
    }}
"""
    else:
        parent, call = "CommonPage", f'super(driver, {jstr(p.name)});'
    title = f" — {jcomment(p.title)}" if p.title else ""
    return f"""package {PKG}.pages;

{imports}
/** {jcomment(p.url)}{title} */
public class {p.name} extends {parent} {{
{_constants(p.elements)}
    public {p.name}(WebDriver driver) {{
        {call}
    }}
{login}}}
"""


