def jstr(s: str) -> str:
    """A Java string literal (JSON escapes are valid Java escapes)."""
    return json.dumps(s, ensure_ascii=False)


def jcomment(text: str) -> str:
    """Safe inside // and /** */ comments: javac reads \\u escapes even in comments."""
    return _comment(text).replace("\\u", "\\ u")


def constant(name: str) -> str:
    """shoppingCartLink -> SHOPPING_CART_LINK"""
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name).upper()


