def build_selenium_project(
    crawl: CrawlResult, test_cases: list[TestCaseIn], plans: list[TestPlan], project_name: str = ""
) -> dict[str, bytes]:
    host = urlparse(crawl.base_url).netloc.replace("www.", "").split(":")[0]
    project = project_name or f"selenium-pom-{re.sub(r'[^a-z0-9]+', '-', host.lower()).strip('-') or 'app'}"
    by_id = {p.test_case_id: p for p in plans}
    for p in crawl.pages:
        if p.name in FRAMEWORK_CLASSES:
            raise ValueError(f"A crawled page is named {p.name}, which clashes with a framework class")
    files: dict[str, bytes] = {}

    def put(path: str, text: str | bytes) -> None:
        files[f"{project}/{path}"] = text if isinstance(text, bytes) else text.encode()

    groups: OrderedDict[str, list] = OrderedDict()
    for tc in test_cases:
        if tc.id in by_id:
            groups.setdefault(tc.requirement_id or "Regression", []).append((tc, by_id[tc.id]))
    taken: set[str] = set()
    classes = [(_class_name(g, taken), g, items) for g, items in groups.items()]

    put("pom.xml", pom_xml(project))
    put("testng.xml", testng_xml([c for c, _, _ in classes]))
    put(".env.example", env_example(crawl))
    put(".gitignore", GITIGNORE)
    put(f"{RES}/config.properties", config_properties(crawl))
    put(f"{SRC}/utils/Config.java", CONFIG_JAVA)
    put(f"{SRC}/utils/TestData.java", TEST_DATA_JAVA)
    put(f"{SRC}/base/DriverFactory.java", DRIVER_FACTORY_JAVA)
    put(f"{SRC}/base/BaseTest.java", BASE_TEST_JAVA)
    put(f"{SRC}/pages/BasePage.java", BASE_PAGE_JAVA)
    common = crawl.common or PageModel(name="CommonPage", url="", elements=[])
    put(f"{SRC}/pages/CommonPage.java", common_page_java(crawl.common))
    put(f"{RES}/object-repository/CommonPage.json", repo_json(common))
    for p in crawl.pages:
        put(f"{SRC}/pages/{p.name}.java", page_java(p))
        put(f"{RES}/object-repository/{p.name}.json", repo_json(p))
    put(f"{RES}/test-data/TestData.xlsx", test_data_xlsx(test_cases, by_id))
    for cls, group, items in classes:
        put(f"{SRC}/tests/{cls}.java", test_class_java(cls, group, items, crawl))
    put("README.md", readme(project, crawl, test_cases, by_id, [c for c, _, _ in classes]))
    return files
