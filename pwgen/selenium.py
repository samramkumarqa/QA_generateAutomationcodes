def _class_name(group: str, taken: set[str]) -> str:
    base = re.sub(r"[^A-Za-z0-9]+", "", group) or "Regression"
    if base[0].isdigit():
        base = "T" + base
    base += "Test"
    name, n = base, 2
    while name in taken:
        name, n = f"{base[:-4]}{n}Test", n + 1
    taken.add(name)
    return name


def _method_name(tc: TestCaseIn, taken: set[str]) -> str:
    base = camel(f"{tc.id} {tc.title}", max_words=10) or "testCase"
    if base in JAVA_KEYWORDS:
        base += "Test"
    name, n = base, 2
    while name in taken:
        name, n = f"{base}{n}", n + 1
    taken.add(name)
    return name


def _step_java(s: PlannedStep, crawl: CrawlResult, keys: dict[str, str], common: str) -> tuple[str, str]:
    """One step as a line of Java, plus the page class whose instance it uses."""
    a = s.action
    if a == "login":
        return f"{var_name(crawl.login_page)}.login();", crawl.login_page
    cls = s.page or common
    v = var_name(cls)
    c = f"{cls}.{constant(s.element)}" if s.element else ""
    d = f"data.get({jstr(keys.get(s.data_key, s.data_key))})" if s.data_key else "null"
    el = s.element or "page"
    count = int(s.value) if s.value.strip().isdigit() else 0
    line = {
        "goto": f"{v}.open();",
        "click": f"{v}.click({c});",
        "fill": f"{v}.type({c}, {d});",
        "select": f"{v}.select({c}, {d});",
        "check": f"{v}.check({c});",
        "uncheck": f"{v}.uncheck({c});",
        "hover": f"{v}.hover({c});",
        "expectVisible": f"Assert.assertTrue({v}.isVisible({c}), {jstr(el + ' should be visible')});",
        "expectHidden": f"Assert.assertTrue({v}.isHidden({c}), {jstr(el + ' should be hidden')});",
        "expectText": f"Assert.assertTrue({v}.containsText({c}, {d}), {jstr(el + ' should contain ')} + {d});",
        "expectValue": f"Assert.assertEquals({v}.value({c}), {d});",
        "expectCount": f"Assert.assertEquals({v}.count({c}), {count});",
        "expectUrlContains": f"Assert.assertTrue({v}.urlContains({jstr(s.value)}), {jstr('URL should contain ' + s.value)});",
        "expectTextOnPage": f"Assert.assertTrue({v}.textOnPage({jstr(s.value)}), {jstr('Page should show ' + s.value)});",
    }[a]
    return line, cls


def test_class_java(class_name: str, group: str, items: list[tuple[TestCaseIn, TestPlan]], crawl: CrawlResult) -> str:
    common = crawl.common.name if crawl.common else "CommonPage"
    methods, taken = [], set()
    for tc, plan in items:
        keys = {d.key: (camel(d.key) or d.key) for d in plan.data}
        body, used = [], []
        current = None
        for i, s in enumerate(plan.steps):
            code, cls = _step_java(s, crawl, keys, common)
            if cls not in used:
                used.append(cls)
            if s.comment:
                body.append(f"        // {jcomment(s.comment)}")
            if s.action == "goto":
                current = s.page
            elif s.action == "login":
                current = None
            elif s.page and s.page != common and s.page != current:
                if i > 0:  # moved to another page: wait for it before touching its elements
                    body.append(f"        {var_name(s.page)}.waitForPage();")
                current = s.page
            body.append(f"        {code}")
        for u in plan.unmapped:
            body.append(f"        // TODO (not automated): {jcomment(u)}")
        if not plan.steps:
            body.append('        throw new SkipException("No steps could be mapped to page elements");')
        elif plan.unmapped:
            # The automated steps above still run (and fail the test if they break), but a test with
            # missing steps must not show as passed: it ends as skipped until the TODOs are done.
            n = len(plan.unmapped)
            body.append(f"        throw new SkipException({jstr(f'{n} step(s) not automated yet: complete the TODOs above')});")
        pages = "\n".join(f"        {c} {var_name(c)} = new {c}(driver);" for c in used)
        title = jcomment(f"{tc.id}: {tc.title}")
        expected = f"\n     * Expected: {jcomment(tc.expected_result)}" if tc.expected_result else ""
        methods.append(
            f"    /**\n     * {title}{expected}\n     */\n"
            f"    @Test(description = {jstr(title)})\n"
            f"    public void {_method_name(tc, taken)}() {{\n"
            f"        if (!TestData.shouldRun({jstr(tc.id)})) throw new SkipException(\"Run = N in test-data/TestData.xlsx\");\n"
            f"        Map<String, String> data = TestData.get({jstr(tc.id)});\n"
            + (pages + "\n" if pages else "")
            + "\n".join(body)
            + "\n    }"
        )
    return f"""package {PKG}.tests;

import java.util.Map;

import org.testng.Assert;
import org.testng.SkipException;
import org.testng.annotations.Test;

import {PKG}.base.BaseTest;
import {PKG}.pages.*;
import {PKG}.utils.TestData;

/** Generated from the approved test cases for {jcomment(group)}. */
public class {class_name} extends BaseTest {{

""" + "\n\n".join(methods) + "\n}\n"


