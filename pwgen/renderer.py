def package_json(name: str) -> str:
    return json.dumps(
        {
            "name": name,
            "version": "1.0.0",
            "private": True,
            "description": "Playwright Page Object Model tests generated by AI Automation Code Generator",
            "scripts": {
                "test": "playwright test",
                "test:headed": "playwright test --headed",
                "test:ui": "playwright test --ui",
                "report": "playwright show-report",
            },
            "devDependencies": {
                "@playwright/test": config.PLAYWRIGHT_VERSION,
                "dotenv": "^16.4.5",
                "exceljs": "^4.4.0",
            },
        },
        indent=2,
    ) + "\n"


