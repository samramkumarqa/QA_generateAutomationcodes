# ---------------------------------------------------------------- page objects

def repo_json(p: PageModel) -> str:
    elements = OrderedDict()
    for e in p.elements:
        d = {"strategy": e.strategy, "value": e.value}
        if e.role:
            d["role"] = e.role
        d["kind"] = e.kind
        d["description"] = e.description
        elements[e.name] = d
    return json.dumps({"page": p.name, "url": p.url, "elements": elements}, indent=2, ensure_ascii=False) + "\n"


def _getters(elements: list[Element]) -> str:
    return "\n".join(
        f"  /** {_comment(e.description)}{'' if e.visible else ' (hidden until opened)'} */\n"
        f"  get {e.name}() {{ return this.el({js(e.name)}); }}\n"
        for e in elements
    )


def _login_parts(p: PageModel) -> tuple[Element | None, Element | None, Element | None]:
    inputs = [e for e in p.elements if e.kind == "input"]
    pwd = next((e for e in inputs if "password" in e.name.lower() or "password" in e.description.lower()), None)
    user = next((e for e in inputs if e is not pwd), None)
    buttons = [e for e in p.elements if e.kind == "button"]
    submit = next((e for e in buttons if re.search(r"log ?in|sign ?in|submit|continue", e.name + e.description, re.I)),
                  buttons[0] if buttons else None)
    return user, pwd, submit


def common_page_js(common: PageModel | None) -> str:
    getters = _getters(common.elements) if common else ""
    return f"""// @ts-check
const {{ BasePage }} = require('./BasePage');
const commonRepo = require('../object-repository/CommonPage.json');

/**
 * Elements shared by the pages after login (header, menu, cart ...).
 * Every page class extends this, so these getters are available on all of them.
 */
class CommonPage extends BasePage {{
  /**
   * @param {{import('@playwright/test').Page}} page
   * @param {{any}} [repo] the page's own object repository
   */
  constructor(page, repo = commonRepo) {{
    super(page, {{ ...repo, elements: {{ ...commonRepo.elements, ...repo.elements }} }});
  }}

{getters}}}

module.exports = {{ CommonPage }};
"""


def page_js(p: PageModel) -> str:
    parent, parent_file = ("BasePage", "./BasePage") if p.is_login else ("CommonPage", "./CommonPage")
    extra = ""
    if p.is_login:
        user, pwd, submit = _login_parts(p)
        if user and pwd and submit:
            extra = f"""
  /**
   * Log in. Defaults to APP_USERNAME / APP_PASSWORD from .env.
   * @param {{string}} [username]
   * @param {{string}} [password]
   */
  async login(username = process.env.APP_USERNAME ?? '', password = process.env.APP_PASSWORD ?? '') {{
    await this.goto();
    await this.{user.name}.fill(username);
    await this.{pwd.name}.fill(password);
    await this.{submit.name}.click();
  }}
"""
    title = f" — {_comment(p.title)}" if p.title else ""
    return f"""// @ts-check
const {{ {parent} }} = require({js(parent_file)});
const repo = require({js('../object-repository/' + p.name + '.json')});

/** {p.url}{title} */
class {p.name} extends {parent} {{
  /** @param {{import('@playwright/test').Page}} page */
  constructor(page) {{
    super(page, repo);
  }}

{_getters(p.elements)}{extra}}}

module.exports = {{ {p.name} }};
"""


def fixtures_js(crawl: CrawlResult) -> str:
    classes = ["CommonPage"] + [p.name for p in crawl.pages]
    requires = "\n".join(f"const {{ {c} }} = require('../pages/{c}');" for c in classes)
    fixtures = "\n".join(
        f"  {fixture_name(c)}: async ({{ page }}, use) => {{ await use(new {c}(page)); }}," for c in classes
    )
    return f"""// @ts-check
/**
 * Page object fixtures: a test asks for {{ loginPage, inventoryPage, ... }} by name
 * and gets a ready instance.
 */
const base = require('@playwright/test');
{requires}

const test = base.test.extend({{
{fixtures}
}});

module.exports = {{ test, expect: base.expect }};
"""


# ---------------------------------------------------------------- specs

def _data_ref(key: str) -> str:
    return f"data.{key}" if JS_IDENT.match(key) else f"data[{js(key)}]"


def _step_js(s: PlannedStep, crawl: CrawlResult, keys: dict[str, str]) -> tuple[str, set[str]]:
    """One step as a line of JS, plus the fixtures it needs."""
    f = fixture_name(s.page) if s.page else ""
    target = f"{f}.{s.element}" if f and s.element else ""
    d = _data_ref(keys.get(s.data_key, s.data_key)) if s.data_key else ""
    a = s.action
    needs = {f} if f else set()
    if a == "login":
        lp = fixture_name(crawl.login_page)
        return f"await {lp}.login();", {lp}
    line = {
        "goto": f"await {f}.goto();",
        "click": f"await {target}.click();",
        "fill": f"await {target}.fill({d});",
        "select": f"await {target}.selectOption({d});",
        "check": f"await {target}.check();",
        "uncheck": f"await {target}.uncheck();",
        "hover": f"await {target}.hover();",
        "expectVisible": f"await expect({target}).toBeVisible();",
        "expectHidden": f"await expect({target}).toBeHidden();",
        "expectText": f"await expect({target}).toContainText({d});",
        "expectValue": f"await expect({target}).toHaveValue({d});",
        "expectCount": f"await expect({target}).toHaveCount({s.value or 0});",
        "expectUrlContains": f"await expect(page).toHaveURL(new RegExp({js(re.escape(s.value))}));",
        "expectTextOnPage": f"await expect(page.getByText({js(s.value)}).first()).toBeVisible();",
    }[a]
    if a in {"expectUrlContains", "expectTextOnPage"}:
        needs.add("page")
    return line, needs


def spec_js(group: str, items: list[tuple[TestCaseIn, TestPlan]], crawl: CrawlResult) -> str:
    tests = []
    for tc, plan in items:
        keys = {d.key: (camel(d.key) or d.key) for d in plan.data}
        lines, fixtures = [], set()
        current = None  # page object the browser is known to be on
        common = crawl.common.name if crawl.common else ""
        for i, s in enumerate(plan.steps):
            code, needs = _step_js(s, crawl, keys)
            fixtures |= needs
            if s.comment:
                lines.append(f"    // {_comment(s.comment)}")
            if s.action == "goto":
                current = s.page
            elif s.action == "login":
                current = None  # wherever the app lands after login
            elif s.page and s.page != common and s.page != current:
                if i > 0:  # moved to another page: wait for it before touching its elements
                    lines.append(f"    await {fixture_name(s.page)}.waitForPage();")
                current = s.page
            lines.append(f"    {code}")
        for u in plan.unmapped:
            lines.append(f"    // TODO (not automated): {_comment(u)}")
        if not plan.steps:
            lines.append("    test.fixme(true, 'No steps could be mapped to page elements');")
        args = ", ".join(sorted(fixtures | {"page"}))
        title = _comment(f"{tc.id}: {tc.title}")
        expected = f"\n    // Expected: {_comment(tc.expected_result)}" if tc.expected_result else ""
        tests.append(
            f"  test({js(title)}, async ({{ {args} }}) => {{\n"
            f"    test.skip(!(await shouldRun({js(tc.id)})), 'Run = N in test-data/TestData.xlsx');\n"
            f"    const data = await getTestData({js(tc.id)});{expected}\n"
            + "\n".join(lines)
            + "\n  });"
        )
    return (
        "// @ts-check\n"
        f"// Generated from the approved test cases for {group}.\n"
        "const { test, expect } = require('../fixtures/pages');\n"
        "const { getTestData, shouldRun } = require('../utils/testData');\n\n"
        f"test.describe({js(group)}, () => {{\n"
        + "\n\n".join(tests)
        + "\n});\n"
    )


def _spec_filename(group: str, taken: set[str]) -> str:
    base = re.sub(r"[^A-Za-z0-9._-]+", "-", group).strip("-") or "tests"
    name, n = base, 2
    while name in taken:
        name, n = f"{base}-{n}", n + 1
    taken.add(name)
    return f"{name}.spec.js"


# ---------------------------------------------------------------- input sheet

def test_data_xlsx(test_cases: list[TestCaseIn], plans: dict[str, TestPlan]) -> bytes:
    wb = Workbook()
    head = PatternFill("solid", fgColor="1F3A5F")
    ws = wb.active
    ws.title = "RunControl"
    ws.append(["TestCaseID", "Title", "Requirement", "Run"])
    for tc in test_cases:
        ws.append([tc.id, tc.title, tc.requirement_id, "Y"])
    dv = DataValidation(type="list", formula1='"Y,N"', allow_blank=False)
    ws.add_data_validation(dv)
    dv.add(f"D2:D{len(test_cases) + 1}")
    ws2 = wb.create_sheet("TestData")
    ws2.append(["TestCaseID", "Key", "Value"])
    for tc in test_cases:
        plan = plans.get(tc.id)
        for d in plan.data if plan else []:
            ws2.append([tc.id, camel(d.key) or d.key, d.value])
    for sheet, widths in ((ws, [14, 60, 14, 8]), (ws2, [14, 24, 50])):
        for cell in sheet[1]:
            cell.font, cell.fill = Font(bold=True, color="FFFFFF"), head
        for i, w in enumerate(widths):
            sheet.column_dimensions["ABCD"[i]].width = w
        sheet.freeze_panes = "A2"
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


# ---------------------------------------------------------------- README

def readme(project: str, crawl: CrawlResult, test_cases: list[TestCaseIn], plans: dict[str, TestPlan]) -> str:
    todo = [(tc.id, u) for tc in test_cases for u in (plans[tc.id].unmapped if tc.id in plans else [])]
    pages = "\n".join(f"| `{p.name}` | `{p.url}` | {len(p.elements)} |" for p in crawl.pages)
    common = f"| `CommonPage` | (every page) | {len(crawl.common.elements)} |\n" if crawl.common else ""
    todo_md = "\n".join(f"- **{i}**: {_comment(u)}" for i, u in todo) or "None: every step was mapped."
    skipped = "\n".join(f"- {s}" for s in crawl.skipped[:30]) or "- None"
    return f"""# {project}

Playwright (JavaScript) Page Object Model tests, generated on {datetime.now():%Y-%m-%d %H:%M}
from {len(test_cases)} approved test cases and a crawl of {crawl.base_url}.

## Setup

```bash
npm install
npx playwright install chromium
cp .env.example .env      # then set APP_USERNAME and APP_PASSWORD
```

## Run

```bash
npm test                  # headless
npm run test:headed       # watch it run
npm run test:ui           # Playwright UI mode
npm run report            # open the HTML report
```

### IntelliJ IDEA / WebStorm
Open this folder as a project, set **Settings → Languages & Frameworks → Node.js** to your Node
installation, then right-click `package.json` → *Show npm Scripts* and run `test`. With the
Playwright plugin (or WebStorm), tests can also be run from the gutter icons in the spec files.

## Structure

```
pages/              Page objects. BasePage resolves locators; CommonPage holds shared header/menu
                    elements; one class per crawled page (getters per element, LoginPage.login()).
object-repository/  Locators as JSON, one file per page. Fix a broken locator here, not in code.
tests/              One spec file per requirement, one test per test case.
fixtures/pages.js   Page objects as Playwright fixtures: async ({{ loginPage, inventoryPage }}) => ...
test-data/          TestData.xlsx: RunControl (Run Y/N per test) and TestData (key/value per test).
utils/testData.js   Reads TestData.xlsx.
playwright.config.js, .env.example, package.json
```

## Pages found

| Page object | URL | Elements |
|---|---|---|
{common}{pages}

Locator preference: `{crawl.test_id_attribute}` test IDs, then stable ids, then role + accessible
name, label, placeholder, then text. Every locator was checked to match exactly one element
when the page was crawled.

## Needs attention

Steps that couldn't be mapped to an element are left as `// TODO` comments in the specs:

{todo_md}

Links not followed during the crawl (kept read-only on purpose):

{skipped}

Pages that only appear after submitting a form, or that need test data to exist, aren't reached
by the crawler; add them as page objects by hand if needed.
"""


# ---------------------------------------------------------------- bundle

def build_project(
    crawl: CrawlResult, test_cases: list[TestCaseIn], plans: list[TestPlan], project_name: str = ""
) -> dict[str, bytes]:
    host = urlparse(crawl.base_url).netloc.replace("www.", "").split(":")[0]
    project = project_name or f"playwright-pom-{re.sub(r'[^a-z0-9]+', '-', host.lower()).strip('-') or 'app'}"
    by_id = {p.test_case_id: p for p in plans}
    files: dict[str, bytes] = {}

    def put(path: str, text: str | bytes) -> None:
        files[f"{project}/{path}"] = text if isinstance(text, bytes) else text.encode()

    put("package.json", package_json(project))
    put("playwright.config.js", playwright_config(crawl))
    put(".env.example", env_example(crawl))
    put(".gitignore", GITIGNORE)
    put("pages/BasePage.js", BASE_PAGE)
    common = crawl.common or PageModel(name="CommonPage", url="", elements=[])
    put("pages/CommonPage.js", common_page_js(crawl.common))
    put("object-repository/CommonPage.json", repo_json(common))
    for p in crawl.pages:
        put(f"pages/{p.name}.js", page_js(p))
        put(f"object-repository/{p.name}.json", repo_json(p))
    put("fixtures/pages.js", fixtures_js(crawl))
    put("utils/testData.js", TEST_DATA_JS)
    put("test-data/TestData.xlsx", test_data_xlsx(test_cases, by_id))

    groups: OrderedDict[str, list] = OrderedDict()
    for tc in test_cases:
        if tc.id in by_id:
            groups.setdefault(tc.requirement_id or "Tests", []).append((tc, by_id[tc.id]))
    taken: set[str] = set()
    for group, items in groups.items():
        put(f"tests/{_spec_filename(group, taken)}", spec_js(group, items, crawl))
    put("README.md", readme(project, crawl, test_cases, by_id))
    return files


def zip_project(files: dict[str, bytes]) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for path, data in files.items():
            z.writestr(path, data)
    return buf.getvalue()
